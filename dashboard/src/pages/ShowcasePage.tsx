import React, { useState } from "react";
import { Navbar } from "../components/layout/Navbar";
import { Footer } from "../components/layout/Footer";
import { LazyVideoPreview } from "../components/landing/LazyVideoPreview";
import { VideoLightbox } from "../components/shared/VideoLightbox";
import { VIRAL_TEMPLATES, type ViralTemplate } from "../config/viralTemplates";
import type { DemoVideoItem } from "../types/saas";
import { Play, Copy, Film } from "lucide-react";

type ShowcasePageProps = {
  authenticated: boolean;
  appDomain: string;
  systemHealthy: boolean;
  demoVideos: DemoVideoItem[];
  onNavigate: (path: string) => void;
};

const CATEGORIES = [
  "All Categories",
  "Business & Monopolies",
  "Finance & Economics",
  "Technology & AI",
  "Geography Explained",
  "Product Explainers",
] as const;

export const ShowcasePage: React.FC<ShowcasePageProps> = ({
  authenticated,
  appDomain,
  systemHealthy,
  demoVideos,
  onNavigate,
}) => {
  const [selectedCategory, setSelectedCategory] = useState<string>("All Categories");
  const [activeLightboxVideo, setActiveLightboxVideo] = useState<DemoVideoItem | null>(null);
  const [activeLightboxTemplate, setActiveLightboxTemplate] = useState<ViralTemplate | null>(null);

  function handleCloneStyle(templateId: string) {
    try {
      window.localStorage.setItem("vms_selected_template", templateId);
    } catch {
      // Ignore storage failure
    }
    onNavigate(authenticated ? "/app" : "/register");
  }

  const filteredVideos = demoVideos.filter((v) => {
    if (selectedCategory === "All Categories") return true;
    if (selectedCategory === "Business & Monopolies") return v.category.toLowerCase().includes("business");
    if (selectedCategory === "Finance & Economics") return v.category.toLowerCase().includes("finance") || v.category.toLowerCase().includes("money");
    if (selectedCategory === "Technology & AI") return v.category.toLowerCase().includes("ai") || v.category.toLowerCase().includes("tech");
    if (selectedCategory === "Geography Explained") return v.category.toLowerCase().includes("geography");
    if (selectedCategory === "Product Explainers") return v.category.toLowerCase().includes("explainer") || v.category.toLowerCase().includes("workflow");
    return true;
  });

  return (
    <div className="vms-landing-root">
      <Navbar
        currentPath="/showcase"
        authenticated={authenticated}
        appDomain={appDomain}
        systemHealthy={systemHealthy}
        onNavigate={onNavigate}
      />

      <main>
        {/* Showcase Header */}
        <section className="vms-section" style={{ paddingBottom: 28 }}>
          <div className="vms-container">
            <div className="vms-page-head">
              <span className="vms-kicker">CINEMATIC VIDEO SHOWCASE</span>
              <h1 className="vms-h1" style={{ margin: "16px 0 20px" }}>
                Real Motion Graphics Rendered at 30 FPS
              </h1>
              <p className="vms-sub" style={{ margin: "0 auto 32px" }}>
                Explore actual video outputs generated by ViralMotionStudio. Click any video to open the
                cinematic player, inspect scene timestamps, and clone the prompt and visual style directly to your studio.
              </p>

              {/* Category Filter Pills */}
              <div className="vms-filter-strip" role="group" aria-label="Showcase categories">
                {CATEGORIES.map((cat) => {
                  const isSelected = selectedCategory === cat;
                  return (
                    <button
                      key={cat}
                      type="button"
                      className={isSelected ? "vms-chip active" : "vms-chip"}
                      onClick={() => setSelectedCategory(cat)}
                    >
                      <span>{cat}</span>
                    </button>
                  );
                })}
              </div>
            </div>
          </div>
        </section>

        {/* Video Grid */}
        <section className="vms-section" style={{ paddingTop: 0 }}>
          <div className="vms-container">
            {filteredVideos.length === 0 ? (
              <div className="vms-empty-state-box">
                <Film size={32} color="var(--vms-text-muted)" />
                <h3>No videos found in this category</h3>
                <p>New compositions are continuously rendered by our pipeline.</p>
                <button
                  type="button"
                  className="vms-btn vms-btn-outline"
                  onClick={() => setSelectedCategory("All Categories")}
                >
                  View All Videos
                </button>
              </div>
            ) : (
              <div className="vms-showcase-gallery-grid">
                {filteredVideos.map((video) => {
                  const matchingTemplate = VIRAL_TEMPLATES.find(
                    (t) => t.demoVideoId === video.id || t.id === video.id
                  );
                  const isLongForm = video.format === "long-form";

                  return (
                    <article
                      key={video.id}
                      className={`vms-showcase-card ${isLongForm ? "wide" : "portrait"}`}
                    >
                      <div className="vms-showcase-card-video">
                        <LazyVideoPreview
                          src={video.mp4Url}
                          poster={video.thumbnailUrl}
                          aspectRatio={isLongForm ? "16 / 9" : "9 / 16"}
                          title={video.title}
                        />
                        <button
                          type="button"
                          className="vms-showcase-expand-btn"
                          aria-label={`Expand ${video.title}`}
                          onClick={() => {
                            setActiveLightboxVideo(video);
                            setActiveLightboxTemplate(matchingTemplate ?? null);
                          }}
                        >
                          <Play size={16} fill="currentColor" />
                          <span>Cinematic View</span>
                        </button>
                      </div>

                      <div className="vms-showcase-card-info">
                        <div className="vms-showcase-card-tags">
                          <span className={isLongForm ? "vms-purple-pill" : "vms-cyan-tag"}>
                            {isLongForm ? "16:9 LONG-FORM" : "9:16 SHORTS"}
                          </span>
                          <span className="vms-mono-tag">{video.durationSec}s · 30 FPS</span>
                        </div>

                        <h3>{video.title}</h3>
                        <p className="vms-showcase-card-desc">{video.category}</p>

                        <div className="vms-showcase-highlights">
                          {video.highlights.map((h) => (
                            <span key={h} className="vms-tag-pill">
                              {h}
                            </span>
                          ))}
                        </div>

                        {matchingTemplate ? (
                          <div className="vms-showcase-card-actions">
                            <button
                              type="button"
                              className="vms-btn vms-btn-outline vms-btn-sm"
                              onClick={() => handleCloneStyle(matchingTemplate.id)}
                            >
                              <Copy size={13} />
                              <span>Clone Style ({matchingTemplate.creditCost} cr)</span>
                            </button>
                          </div>
                        ) : null}
                      </div>
                    </article>
                  );
                })}
              </div>
            )}
          </div>
        </section>
      </main>

      <Footer appDomain={appDomain} onNavigate={onNavigate} />

      {activeLightboxVideo ? (
        <VideoLightbox
          video={activeLightboxVideo}
          template={activeLightboxTemplate}
          onClose={() => {
            setActiveLightboxVideo(null);
            setActiveLightboxTemplate(null);
          }}
          onCloneStyle={handleCloneStyle}
        />
      ) : null}
    </div>
  );
};
